def test_missing_values():
    assert split_high_risk_time(None) == ("", None)
    t, rest = split_high_risk_time(float("nan"))
    assert t == "" and pd.isna(rest)


def test_extract_adds_column_right_after_safety():
    df = pd.DataFrame({
        "작업내용": ["a", "b"],
        SAFETY_COL: ["고위험 작업시간: 09:00 ~ 10:00 안전모", "안전모"],
        "현장책임자": ["x", "y"],
    })
    out = extract_high_risk_time(df)
    assert list(out.columns) == ["작업내용", SAFETY_COL, HIGH_RISK_COL, "현장책임자"]
    assert list(out[HIGH_RISK_COL]) == ["09:00 ~ 10:00", ""]
    assert list(out[SAFETY_COL]) == ["안전모", "안전모"]
    assert df[SAFETY_COL][0].startswith("고위험")   # 원본은 건드리지 않는다


def test_extract_without_safety_column_is_noop():
    df = pd.DataFrame({"작업내용": ["a"]})
    assert list(extract_high_risk_time(df).columns) == ["작업내용"]


def test_process_respects_option():
    df = pd.DataFrame({SAFETY_COL: ["9시~10시 안전모"]})
    off = process(df, Preset(name="p", department_code="x"))
    assert HIGH_RISK_COL not in off.columns
    on = process(df, Preset(name="p", department_code="x", extract_high_risk_time=True))
    assert on[HIGH_RISK_COL][0] == "09:00 ~ 10:00"
    assert on[SAFETY_COL][0] == "안전모"
